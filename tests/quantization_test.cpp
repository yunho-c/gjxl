struct StrategyMatrixCase {
  AcStrategyType strategy;
  gjxl::Extent2D extent;
  gjxl::Extent2D low_frequency_extent;
};

constexpr std::array kStrategyMatrixCases = {
  StrategyMatrixCase{AcStrategyType::kDct8, {8, 8}, {1, 1}},
  StrategyMatrixCase{AcStrategyType::kDct16x16, {16, 16}, {2, 2}},
  StrategyMatrixCase{AcStrategyType::kDct32x32, {32, 32}, {4, 4}},
  StrategyMatrixCase{AcStrategyType::kDct16x8, {16, 8}, {2, 1}},
  StrategyMatrixCase{AcStrategyType::kDct8x16, {16, 8}, {2, 1}},
  StrategyMatrixCase{AcStrategyType::kDct32x16, {32, 16}, {4, 2}},
  StrategyMatrixCase{AcStrategyType::kDct16x32, {32, 16}, {4, 2}},
};

bool CheckDefaultMatrices() {
  constexpr std::array channels = {
    XybChannel::kX,
    XybChannel::kY,
    XybChannel::kB,
  };

  for (const StrategyMatrixCase& test : kStrategyMatrixCases) {
    for (const XybChannel channel : channels) {
      gjxl::QuantizationMatrixView matrix;
      const gjxl::Status status = gjxl::GetDefaultQuantizationMatrix(
        test.strategy,
        channel,
        &matrix);

      const size_t count = test.extent.width * test.extent.height;
      if (!status.ok() ||
          matrix.coefficient_extent != test.extent ||
          matrix.low_frequency_extent != test.low_frequency_extent ||
          matrix.dequant.size() != count ||
          matrix.inverse_dequant.size() != count) {

        std::cerr << "Quantization matrix geometry is incorrect\n";
        return false;
      }

      for (size_t y = 0; y < test.extent.height; ++y) {
        for (size_t x = 0; x < test.extent.width; ++x) {
          const size_t index = y * test.extent.width + x;
          const bool is_low_frequency =
            x < test.low_frequency_extent.width &&
            y < test.low_frequency_extent.height;

          if (!(matrix.dequant[index] > 0.0f) ||
              (is_low_frequency && matrix.inverse_dequant[index] != 0.0f) ||
              (!is_low_frequency &&
               std::abs(
                 matrix.dequant[index] * matrix.inverse_dequant[index] -
                 1.0f) > 2.0e-7f)) {

            std::cerr << "Quantization matrix contents are invalid\n";
            return false;
          }
        }
      }
    }
  }

  for (const MatrixHashGolden& golden : kMatrixHashGoldens) {
    gjxl::QuantizationMatrixView matrix;
    const gjxl::Status status = gjxl::GetDefaultQuantizationMatrix(
      golden.strategy,
      golden.channel,
      &matrix);

    if (!status.ok() ||
        HashFloats(matrix.dequant) != golden.dequant_hash ||
        HashFloats(matrix.inverse_dequant) != golden.inverse_dequant_hash) {

      std::cerr
        << "Default matrix differs from libjxl "
        << kPinnedLibjxlRevision
        << '\n';
      return false;
    }
  }

  gjxl::QuantizationMatrixView dct16x8;
  gjxl::QuantizationMatrixView dct8x16;
  gjxl::QuantizationMatrixView dct32x16;
  gjxl::QuantizationMatrixView dct16x32;

  if (!gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct16x8,
        XybChannel::kY,
        &dct16x8).ok() ||
      !gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct8x16,
        XybChannel::kY,
        &dct8x16).ok() ||
      !gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct32x16,
        XybChannel::kY,
        &dct32x16).ok() ||
      !gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct16x32,
        XybChannel::kY,
        &dct16x32).ok() ||
      dct16x8.dequant.data() != dct8x16.dequant.data() ||
      dct16x8.inverse_dequant.data() != dct8x16.inverse_dequant.data() ||
      dct32x16.dequant.data() != dct16x32.dequant.data() ||
      dct32x16.inverse_dequant.data() != dct16x32.inverse_dequant.data()) {

    std::cerr << "Transpose strategies do not share canonical matrices\n";
    return false;
  }

  gjxl::QuantizationMatrixView unused;
  if (gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kIdentity,
        XybChannel::kY,
        &unused).ok() ||
      gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct8,
        static_cast<XybChannel>(255),
        &unused).ok() ||
      gjxl::GetDefaultQuantizationMatrix(
        AcStrategyType::kDct8,
        XybChannel::kY,
        nullptr).ok()) {

    std::cerr << "Invalid matrix request was accepted\n";
    return false;
  }

  return true;
}

constexpr std::array<float, 12> kQuantField = {
  0.75f, 1.25f, 2.0f, 3.5f,
  4.0f, 5.25f, 6.5f, 8.0f,
  9.5f, 12.0f, 16.0f, 21.0f,
};

void StoreQuantField(std::array<float, 18>* storage) {
  storage->fill(-1.0f);
  for (size_t y = 0; y < 3; ++y) {
    for (size_t x = 0; x < 4; ++x) {
      (*storage)[y * 6 + x] = kQuantField[y * 4 + x];
    }
  }
}

bool CheckRawField(
  const std::array<int32_t, 18>& storage,
  std::span<const int32_t, 12> expected) {

  for (size_t y = 0; y < 3; ++y) {
    for (size_t x = 0; x < 4; ++x) {
      if (storage[y * 6 + x] != expected[y * 4 + x]) {
        return false;
      }
    }
    if (storage[y * 6 + 4] != -777 || storage[y * 6 + 5] != -777) {
      return false;
    }
  }
  return true;
}

bool CheckQuantizerAndFields() {
  gjxl::Quantizer direct;
  if (!gjxl::Quantizer::Create({1024, 64}, &direct).ok() ||
      !direct.valid() ||
      direct.scale() != 0.015625f ||
      direct.inverse_global_scale() != 64.0f ||
      direct.dc_steps() !=
        std::array<float, 3>{1.0f / 4096.0f, 1.0f / 512.0f, 1.0f / 256.0f} ||
      direct.inverse_dc_steps() !=
        std::array<float, 3>{4096.0f, 512.0f, 256.0f}) {

    std::cerr << "Direct quantizer construction is incorrect\n";
    return false;
  }

  gjxl::Quantizer unused;
  if (gjxl::Quantizer::Create({0, 64}, &unused).ok() ||
      gjxl::Quantizer::Create({32769, 64}, &unused).ok() ||
      gjxl::Quantizer::Create({1024, 0}, &unused).ok() ||
      gjxl::Quantizer::Create({1024, 65537}, &unused).ok() ||
      gjxl::Quantizer::Create({1024, 64}, nullptr).ok()) {

    std::cerr << "Invalid quantizer parameters were accepted\n";
    return false;
  }

  std::array<int32_t, 18> raw_storage;
  raw_storage.fill(-777);
  const gjxl::PlaneI32View raw{
    .data = raw_storage.data(),
    .extent = {4, 3},
    .stride = 6,
  };

  gjxl::Quantizer uniform;
  if (!gjxl::CreateUniformQuantizer(1.7f, 3.25f, raw, &uniform).ok() ||
      uniform.params().global_scale != 11141 ||
      uniform.params().quant_dc != 10) {

    std::cerr << "Uniform quantizer differs from pinned libjxl\n";
    return false;
  }

  constexpr std::array<int32_t, 12> kUniformRaw = {
    19, 19, 19, 19,
    19, 19, 19, 19,
    19, 19, 19, 19,
  };
  if (!CheckRawField(raw_storage, kUniformRaw)) {
    std::cerr << "Uniform raw quant field is incorrect\n";
    return false;
  }

  std::array<float, 18> field_storage;
  StoreQuantField(&field_storage);
  const gjxl::ConstPlaneF32View field{
    .data = field_storage.data(),
    .extent = {4, 3},
    .stride = 6,
  };

  raw_storage.fill(-777);
  gjxl::Quantizer adaptive;
  if (!gjxl::CreateQuantizerFromField(
        1.7f,
        field,
        raw,
        &adaptive).ok() ||
      adaptive.params().global_scale != 11141 ||
      adaptive.params().quant_dc != 10) {

    std::cerr << "Quant field conversion differs from pinned libjxl\n";
    return false;
  }

  constexpr std::array<int32_t, 12> kAdaptiveRaw = {
    4, 7, 12, 21,
    24, 31, 38, 47,
    56, 71, 94, 124,
  };
  if (!CheckRawField(raw_storage, kAdaptiveRaw)) {
    std::cerr << "Adaptive raw quant field is incorrect\n";
    return false;
  }

  raw_storage.fill(-777);
  if (!gjxl::CreateQuantizerFromField(
        20.0f,
        field,
        raw,
        &adaptive).ok() ||
      adaptive.params().global_scale != 26214 ||
      adaptive.params().quant_dc != 50) {

    std::cerr << "Uncapped quant field statistics are incorrect\n";
    return false;
  }

  constexpr std::array<int32_t, 12> kUncappedRaw = {
    2, 3, 5, 9,
    10, 13, 16, 20,
    24, 30, 40, 53,
  };
  if (!CheckRawField(raw_storage, kUncappedRaw)) {
    std::cerr << "Uncapped raw quant field is incorrect\n";
    return false;
  }

  field_storage[0] = 0.0f;
  if (gjxl::CreateQuantizerFromField(
        1.7f,
        field,
        raw,
        &unused).ok() ||
      gjxl::CreateUniformQuantizer(
        1.7f,
        std::numeric_limits<float>::infinity(),
        raw,
        &unused).ok()) {

    std::cerr << "Invalid quant field was accepted\n";
    return false;
  }

  return true;
}


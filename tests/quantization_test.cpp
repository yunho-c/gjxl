constexpr std::string_view kPinnedLibjxlRevision =
  "e8ff09762481785938d8e4e01333ed3917571161";

uint32_t FloatBits(float value) {
  return std::bit_cast<uint32_t>(value);
}

uint64_t HashQuantized(std::span<const int32_t> values) {
  uint64_t hash = 1469598103934665603ull;
  for (const int32_t value : values) {
    hash ^= static_cast<uint32_t>(value);
    hash *= 1099511628211ull;
  }
  return hash;
}

uint64_t HashFloats(std::span<const float> values) {
  uint64_t hash = 1469598103934665603ull;
  for (const float value : values) {
    hash ^= FloatBits(value);
    hash *= 1099511628211ull;
  }
  return hash;
}

